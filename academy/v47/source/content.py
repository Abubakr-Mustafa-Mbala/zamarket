# ZaMarket Academy — affiliate course content (V47).
# Every lesson is written from how ZaMarket actually works today. Facts that
# change (commission rates, payout minimum, delivery windows) are never given
# as numbers here: affiliates are taught where to read them on the site.

def L(id, title, mins, icon, image, outcome, notes, demo, practice, q, a, fac, key_points=None):
    return dict(id=id, title=title, duration_minutes=mins, icon=icon, image=image,
                learning_outcome=outcome, key_points=key_points or [], teaching_notes=notes,
                demonstration=demo, practice=practice,
                knowledge_check=dict(question=q, answer=a), facilitator_note=fac)

MODULES = []

def M(number, title, icon, summary, lessons):
    MODULES.append(dict(number=number, title=title, icon=icon, cover=f"images/module-{number:02d}.jpg", summary=summary, lessons=lessons))

